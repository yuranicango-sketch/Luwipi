assert.equal(P.dueReviews(profile,"2026-10-10").length,1);
assert.throws(()=>P.completeReview(profile,due[0],"2026-10-08",true),/vencida/);
step=P.completeReview(profile,P.dueReviews(profile,"2026-10-10")[0],"2026-10-10",false);profile=step.profile;
assert.equal(step.nextDue,"2026-10-11","Low-confidence review retries tomorrow without advancing");
