import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import "../assets/pedagogy/sightreading-foundation-v1.js";
const P=globalThis.LuwipiPedagogyV1,read=path=>readFile(new URL("../"+path,import.meta.url),"utf8");
let profile=P.newProfile();
const pattern="Síncopa no contratempo",start="2026-10-01";
profile.mistakes.push({track:"F",level:0,pattern,lastSeen:start,due:P.dueDates(start)});
