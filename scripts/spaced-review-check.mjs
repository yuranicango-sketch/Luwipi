assert.equal(step.nextDue,"2026-10-22");
step=P.completeReview(profile,P.dueReviews(profile,"2026-10-22")[0],"2026-10-22",true);profile=step.profile;
assert.equal(step.completed,true);
assert.equal(profile.mistakes[0].review.history.length,5,"Pass/fail history must be retained");
assert.equal(P.dueReviews(profile,"2027-01-01").length,0,"Completed reviews must NOT remain permanently overdue");
const relapsed=P.record(profile,{track:"F",level:0,sessionId:"new-error",exerciseId:"rhythm-example",
 date:"2026-10-23",kind:"practice",notes:.65,rhythm:.8,stops:1,bpm:60,stablePulse:false,
 evidence:"self_report",errors:[{pattern}]}).profile;
assert.equal(relapsed.mistakes[0].review.next,0,"A repeated error must begin a fresh learning cycle");
