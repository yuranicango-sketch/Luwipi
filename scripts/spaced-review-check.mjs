assert.ok(ui.includes("P.dueReviews(profile,todayLocal())")&&ui.includes("P.completeReview(profile,reviewed,attempt.date,practised)"));
assert.ok(ui.includes("reviewCoverage?.value!=='1'"),"The user must verify that the score really covers the error pattern");
