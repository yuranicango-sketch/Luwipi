assert.equal(relapsed.mistakes[0].review.history.length,0);
const endpoint=await read("api/sightreading-progress.js");
const sanitize=new Function(endpoint.replace("export async function GET","async function GET")
 .replace("export async function PUT","async function PUT")+";return sanitize;")();
